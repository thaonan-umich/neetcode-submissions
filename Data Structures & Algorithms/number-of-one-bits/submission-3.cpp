// 最终方法
/*
n     = 10110100
              ↑ 最右边的 1

n - 1 = 10110011

AND:
        10110100
      & 10110011
      ----------
        10110000
*/

class Solution {
public:
    int hammingWeight(uint32_t n) {

        int count = 0;

        while (n) {
            n &= (n-1); // 每次干掉最右边的1，直到全部都是0
            ++count;
        }

        return count;
    }
};
